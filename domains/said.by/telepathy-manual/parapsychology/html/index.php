<h2><a name="Telepathy">Telepathy</a></h2>	

<h3><a name="Tvocabulary">T-Vocabulary</a></h3>

<p>
Telepathy is a form of communication without sound or bodylanguage queues between intelligent beings.<br/>
In order for it to make sense in writing, we simply put "t-" before any verb or noun otherwise used in communicating ideas.<br/>
Examples:<br/>
<ul>
	<li>t-work = work related to telepathy (research).</li>
	<li>t-unavailable = individual is unavailable for telepathic comms.</li>
	<li>t-deny = telepathic denial of a stated fact.</li>
</ul>
</p>

<h3><a name="TgroupNames">T-Group-Names</a></h3>

<p>
Telepathic communication can happen between individuals, or between groups of individuals.<br/>
To facilitate the very dynamic process of telepathic group communication, t-group-names are introduced.<br/>
</p>

<p>
<ul>
	<li>t-group-names are time- and place-sensitive, they can also vary wildly in membership over long and short timespans.</li>
	<li>it is quite possible to have multiple t-group-names for exactly the same or slightly different compositions of membership (full and partial synonyms).</li>
	<li>t-group-names can be combined with nouns and verbs in any linguistic way of course.</li>
</ul>
</p>

